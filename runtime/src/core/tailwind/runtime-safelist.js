function spacingUtilities(prefixes) {
  return prefixes.flatMap(prefix => spacingKeys.map(key => `${prefix}-${key}`))
}

function colorUtilities(prefixes) {
  const colors = [
    ...tailwindStaticColorKeys,
    ...tailwindDefaultColorKeys.flatMap(color => tailwindDefaultScaleKeys.map(scale => `${color}-${scale}`)),
    ...semanticColorKeys,
    ...accentKeys,
    ...accentKeys.flatMap(accent => accentScaleKeys.map(scale => `${accent}-${scale}`)),
  ]
  return prefixes.flatMap(prefix => colors.flatMap(color => [
    `${prefix}-${color}`,
    ...opacityKeys.map(opacity => `${prefix}-${color}/${opacity}`),
  ]))
}

function numberedUtilities(prefix, values) {
  return values.map(value => `${prefix}-${value}`)
}

