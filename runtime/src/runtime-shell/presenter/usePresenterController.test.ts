// @vitest-environment jsdom
/** 文件功能：验证唯一观众控制器、有限意图、重开对齐、新 owner 接管与无旧命令恢复。 */
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { cleanupPresenterFixture, flushPresenterMessages, mountPresenter, preparePresenterFixture } from './presenter-test-helpers'
beforeEach(preparePresenterFixture)
afterEach(cleanupPresenterFixture)
describe('Presenter 控制器', () => {
  it.each(['console', 'display'] as const)('%s 先加载也能握手，只有观众执行意图', async first => {
    const actions = vi.fn(), display = first === 'display' ? mountPresenter('display', 10, actions) : null
    const consoleView = mountPresenter('console', 1)
    const audience = display ?? mountPresenter('display', 10, actions)
    await flushPresenterMessages()
    expect(consoleView.controller.remotePlayback.value?.phase).toBe('stopped')
    expect(consoleView.controller.currentPage.value?.speakerNotes).toBe('备注')
    for (const action of ['start', 'hold', 'release', 'next', 'stop'] as const) consoleView.controller.sendPlaybackCommand(action)
    await flushPresenterMessages()
    expect(actions.mock.calls.map(call => call[0])).toEqual(['start', 'hold', 'release', 'next', 'stop'])
    audience.controller.updatePlayback({ page: '/b', phase: 'blocked', held: true, issue: { code: 'MEDIA_PERMISSION', message: '请在观众窗口允许播放' } })
    await flushPresenterMessages()
    expect(consoleView.controller.currentPath.value).toBe('/b')
    expect(consoleView.controller.remotePlayback.value).toMatchObject({ page: '/b', phase: 'blocked', held: true, issue: { code: 'MEDIA_PERMISSION' } })
  })
  it('控制台导航等待观众事实，重开获得当前状态，不重放 start/next', async () => {
    const actions = vi.fn(), audience = mountPresenter('display', 10, actions), first = mountPresenter('console', 1)
    await flushPresenterMessages()
    first.controller.navigateTo('/b')
    expect(first.controller.currentPath.value).toBe('/a')
    await flushPresenterMessages()
    expect(first.controller.currentPath.value).toBe('/b')
    first.controller.sendPlaybackCommand('start'); await flushPresenterMessages()
    audience.controller.updatePlayback({ page: '/b', phase: 'playing', held: true, issue: null }); await flushPresenterMessages()
    first.app.unmount()
    const reopened = mountPresenter('console', 2); await flushPresenterMessages()
    expect(reopened.controller.remotePlayback.value).toMatchObject({ page: '/b', phase: 'playing', held: true })
    expect(actions).toHaveBeenCalledTimes(1)
  })
  it('新观众 owner 接管后旧观众停止且失去发布与执行权', async () => {
    const oldActions = vi.fn(), newActions = vi.fn(), old = mountPresenter('display', 10, oldActions), consoleView = mountPresenter('console', 1)
    await flushPresenterMessages()
    const newer = mountPresenter('display', 11, newActions); await flushPresenterMessages()
    expect(oldActions).toHaveBeenCalledWith('stop')
    const owner = consoleView.controller.remotePlayback.value?.ownerId
    old.controller.updatePlayback({ page: '/b', phase: 'playing', held: false, issue: null })
    consoleView.controller.sendPlaybackCommand('next'); await flushPresenterMessages()
    expect(consoleView.controller.remotePlayback.value?.ownerId).toBe(owner)
    expect(newActions).toHaveBeenCalledWith('next')
    expect(oldActions).toHaveBeenCalledTimes(1)
    newer.app.unmount(); await flushPresenterMessages()
    expect(consoleView.controller.displayStatus.value.state).toBe('closed')
  })
  it('没有观众时意图不排队，thumbnail 设置只影响控制台 UI', async () => {
    localStorage.setItem('web-presentation.presenter.sync.test', JSON.stringify({ protocol: 4, type: 'playback-command', action: 'next' }))
    const consoleView = mountPresenter('console', 1), actions = vi.fn()
    consoleView.controller.sendPlaybackCommand('next')
    consoleView.controller.setTileSize(999)
    expect(consoleView.controller.tileSize.value).toBe(420)
    mountPresenter('display', 10, actions); await flushPresenterMessages()
    expect(actions).not.toHaveBeenCalled()
    expect(consoleView.controller.currentPath.value).toBe('/a')
  })
})
